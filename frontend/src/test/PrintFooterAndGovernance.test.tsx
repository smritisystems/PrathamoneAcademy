import React from 'react'
import { describe, it, expect } from 'vitest'
import { render, screen } from '@testing-library/react'
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import PrintFooter from '../components/printing/PrintFooter'
import { PrintBrandingFooter, PrintDocumentHeader, PrintDocumentSignatory } from '../components/PrintDocumentBranding'
import { PRINT_SHARE_BRANDING } from '../config/branding'
import { createDefaultPrintSettings } from '../config/printPresets'
import { generateUniversalPrintCss, calculatePrintLayout } from '../services/printLayoutEngine'

function renderWithClient(ui: React.ReactElement) {
  const queryClient = new QueryClient({
    defaultOptions: { queries: { retry: false } },
  })
  return render(<QueryClientProvider client={queryClient}>{ui}</QueryClientProvider>)
}

describe('Global Print Footer & Governance Engine (RULE 010 & Global Print Standard)', () => {
  describe('Canonical PrintFooter Component', () => {
    it('renders the exact Two-Row standard: Row 1 Right-Aligned, Row 2 Center-Aligned', () => {
      renderWithClient(
        <PrintFooter
          documentId="DOC-001"
          pageNumber={1}
          totalPages={2}
          classification="Confidential"
        />
      )

      // Verify Footer Container
      const footer = screen.getByTestId('pratham-global-print-footer')
      expect(footer).toBeDefined()

      // ── Row 1 (Right-Aligned): Confidential · Document ID: DOC-001 · Page 1 of 2 ──
      const row1 = screen.getByTestId('print-footer-row-1')
      expect(row1).toBeDefined()
      expect(row1.className).toContain('justify-end')
      expect(row1.className).toContain('text-right')
      expect(row1.textContent).toContain('Confidential')
      expect(row1.textContent).toContain('Document ID: DOC-001')
      expect(row1.textContent).toContain('Page 1 of 2')

      // ── Row 2 (Center-Aligned): Generated by PrathamOne EduOS · © PrathamOne EduOS ──
      const row2 = screen.getByTestId('print-footer-row-2')
      expect(row2).toBeDefined()
      expect(row2.className).toContain('text-center')
      expect(row2.textContent).toBe('Generated by PrathamOne EduOS · © PrathamOne EduOS')
    })

    it('supports dynamic confidentiality classifications and document identifiers', () => {
      renderWithClient(
        <PrintFooter
          documentId="RCP-2026-9901"
          classification="Official Fee Voucher"
          pageNumber={1}
          totalPages={1}
        />
      )

      const row1 = screen.getByTestId('print-footer-row-1')
      expect(row1.textContent).toContain('Official Fee Voucher')
      expect(row1.textContent).toContain('Document ID: RCP-2026-9901')
      expect(row1.textContent).toContain('Page 1 of 1')
    })

    it('supports multi-page repeating fixed footer mode', () => {
      const { container } = renderWithClient(
        <PrintFooter
          documentId="EMP-042"
          classification="Strictly Confidential"
          fixedBottom={true}
        />
      )

      const footer = container.querySelector('[data-testid="pratham-global-print-footer"]')
      expect(footer?.className).toContain('print:fixed')
      expect(footer?.className).toContain('print:bottom-0')
      expect(footer?.className).toContain('print:left-0')
      expect(footer?.className).toContain('print:right-0')
    })

    it('allows toggling software branding row when contractually configured', () => {
      renderWithClient(
        <PrintFooter
          documentId="CERT-777"
          classification="Official Merit Certificate"
          showSoftwareBranding={false}
        />
      )

      expect(screen.queryByTestId('print-footer-row-2')).toBeNull()
      expect(screen.getByTestId('print-footer-row-1')).toBeDefined()
    })
  })

  describe('Integration with PrintDocumentBranding Barrel', () => {
    it('PrintBrandingFooter delegates to PrintFooter when document metadata is supplied', () => {
      renderWithClient(
        <PrintBrandingFooter
          documentId="VCH-2026-003"
          classification="Faculty Remuneration Statement"
          pageNumber={1}
          totalPages={3}
        />
      )

      expect(screen.getByTestId('pratham-global-print-footer')).toBeDefined()
      const row1 = screen.getByTestId('print-footer-row-1')
      expect(row1.textContent).toContain('Faculty Remuneration Statement')
      expect(row1.textContent).toContain('Document ID: VCH-2026-003')
      expect(row1.textContent).toContain('Page 1 of 3')
      expect(screen.getByTestId('print-footer-row-2')).toBeDefined()
    })

    it('PrintDocumentSignatory accepts and passes documentRef and classification to footer', () => {
      renderWithClient(
        <PrintDocumentSignatory
          collectorName="Accounts Desk"
          documentRef="EXAM-10A01"
          classification="Official Academic Transcript"
        />
      )

      expect(screen.getByTestId('pratham-global-print-footer')).toBeDefined()
      const row1 = screen.getByTestId('print-footer-row-1')
      expect(row1.textContent).toContain('Official Academic Transcript')
      expect(row1.textContent).toContain('Document ID: EXAM-10A01')
    })
  })

  describe('Decoupled Institution Branding vs Software Branding', () => {
    it('keeps institution name, address, contact separate from software branding', () => {
      renderWithClient(
        <div>
          <PrintDocumentHeader
            title="ADMISSION ENQUIRY FORM"
            documentRef="ENQ-2026-001"
            institution={{
              name: 'Prashant Academy Coaching Institute',
              code: 'PA-HQ',
              phone: '+91-9876543210',
              address: 'Malad West',
            }}
          />
          <div className="p-4">Form Body Content</div>
          <PrintFooter
            documentId="ENQ-2026-001"
            classification="Confidential CRM Enquiry"
          />
        </div>
      )

      // Institution Branding Header
      expect(screen.getByText(/Prashant Academy Coaching Institute/i)).toBeDefined()
      expect(screen.getByText(/CODE: PA-HQ/i)).toBeDefined()
      expect(screen.getByText(/Ph: \+91-9876543210/i)).toBeDefined()

      // Software Branding Footer
      const row2 = screen.getByTestId('print-footer-row-2')
      expect(row2.textContent).toBe('Generated by PrathamOne EduOS · © PrathamOne EduOS')

      // Ensure no confusion between the two
      expect(row2.textContent).not.toContain('Prashant Academy')
    })
  })

  describe('Universal Print Layout Engine CSS Generation', () => {
    it('generates standard print CSS containing two-row footer rules and page counters', () => {
      const settings = createDefaultPrintSettings('report_card')
      const layout = calculatePrintLayout({ width: 794, height: 1123 }, settings)
      const css = generateUniversalPrintCss(layout, settings)

      expect(css).toContain('.pratham-global-print-footer')
      expect(css).toContain('[data-testid="print-footer-row-1"]')
      expect(css).toContain('[data-testid="print-footer-row-2"]')
      expect(css).toContain('.pratham-page-num::after')
      expect(css).toContain('counter(page)')
      expect(css).toContain('counter(pages)')
    })
  })
})
