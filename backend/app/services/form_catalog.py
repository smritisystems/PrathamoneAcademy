def get_form_definition(form_id: str) -> Dict[str, Any]:
    """Retrieve form definition by ID, or raise ValueError if not found."""
    if form_id not in FORM_CATALOGUE:
        raise ValueError(f"Form '{form_id}' is not recognized in the form catalog.")
    return FORM_CATALOGUE[form_id]

def list_form_definitions(entity: str = None, category: str = None) -> List[Dict[str, Any]]:
    """List all available form definitions with optional entity and category filters."""
    result = []
    for form in FORM_CATALOGUE.values():
        if entity and form["entity"].lower() != entity.lower():
            continue
        if category and form["category"].lower() != category.lower():
            continue
        result.append(form)
    return result

