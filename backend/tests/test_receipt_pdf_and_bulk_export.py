class TestReceiptPdfUtilities:
    """Unit tests for PDF filename sanitization and INR currency phrasing."""

    def test_sanitize_receipt_filename(self):
        assert sanitize_receipt_filename("Aarav Sharma", "RCP-2026-0001") == "Aarav_Sharma_RCP-2026-0001.pdf"
        assert sanitize_receipt_filename("Priya  Patel  ", "REC/2026/042") == "Priya_Patel_REC_2026_042.pdf"
        assert sanitize_receipt_filename("John Doe: Senior*", "TXN-001?*") == "John_Doe_Senior_TXN-001.pdf"
        assert sanitize_receipt_filename("", "") == "Student_Receipt.pdf"

    def test_number_to_words_inr(self):
        assert number_to_words_inr(0) == "Rupees Zero Only"
        assert number_to_words_inr(500) == "Rupees Five Hundred Only"
        assert number_to_words_inr(15000) == "Rupees Fifteen Thousand Only"
        assert number_to_words_inr(25450) == "Rupees Twenty Five Thousand Four Hundred Fifty Only"
        assert number_to_words_inr(105000) == "Rupees One Lakh Five Thousand Only"
        assert number_to_words_inr(10000000) == "Rupees One Crore Only"


